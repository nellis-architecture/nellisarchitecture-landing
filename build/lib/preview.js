const fs = require('node:fs');
const path = require('node:path');
const { PAGES, readSite } = require('./pages');
const news = require('./pages/news');
const contact = require('./pages/contact');

const HEADER = '/* Generated by npm run build (build/lib/preview.js). Do not edit. */\n';
const PARTIALS = 'build/lib/partials';
const DATA = ['data/projects.json', 'data/search.json'];
const MANIFEST = 'build/images.json';

/* Posix path relative to root: the same text on Windows and on Linux. */
const key = (root, file) => path.relative(root, file).split(path.sep).join('/');

const moduleFile = (mod) => Object.values(require.cache).find((m) => m.exports === mod).filename;

/* The CMS preview pages: PAGES without the news index (needs the posts) and contact. */
function previewPages(root) {
  return PAGES.filter((p) => p.module !== news && p.module !== contact).map((p) => ({
    content: p.content, slug: p.slug, category: p.category, file: key(root, moduleFile(p.module)),
  }));
}

/* The page modules and every local module they require, keyed and sorted. */
function moduleSources(root, files) {
  const out = {};
  const todo = [...files];
  while (todo.length) {
    const file = todo.pop();
    if (!out[file]) {
      out[file] = fs.readFileSync(path.join(root, file), 'utf8');
      [...out[file].matchAll(/require\('(\.[^']+)'\)/g)]
        .forEach((m) => todo.push(`${path.posix.join(path.posix.dirname(file), m[1])}.js`));
    }
  }
  return Object.fromEntries(Object.keys(out).sort().map((k) => [k, out[k]]));
}

/* The files the renderers read, as text: the partials, the data and the manifest. */
function dataFiles(root, manifest) {
  const partials = fs.readdirSync(path.join(root, PARTIALS)).filter((f) => f.endsWith('.html'))
    .map((f) => `${PARTIALS}/${f}`);
  const files = Object.fromEntries([...partials, ...DATA]
    .map((f) => [f, fs.readFileSync(path.join(root, f), 'utf8')]));
  files[MANIFEST] = JSON.stringify(manifest);
  return Object.fromEntries(Object.keys(files).sort().map((k) => [k, files[k]]));
}

/* ---------- browser side: self-contained, embedded with `${fn}` ---------- */

/* Only the node:path functions the render modules call, posix. */
function pathShim() {
  function normalize(p) {
    const abs = p.charAt(0) === '/';
    const out = [];
    p.split('/').forEach((s) => {
      if (!s || s === '.') return;
      if (s === '..' && out.length && out[out.length - 1] !== '..') out.pop();
      else if (s !== '..' || !abs) out.push(s);
    });
    let r = out.join('/');
    if (!r && !abs) r = '.';
    if (r && p.length > 1 && p.charAt(p.length - 1) === '/') r += '/';
    return abs ? `/${r}` : r;
  }
  const trim = (p) => (p.length > 1 ? p.replace(/\/+$/, '') : p);
  function join(...parts) {
    const s = parts.filter((x) => x !== '').join('/');
    return s ? normalize(s) : '.';
  }
  function dirname(p) {
    const t = trim(p);
    const i = t.lastIndexOf('/');
    if (i < 0) return '.';
    return i ? t.slice(0, i) : '/';
  }
  function basename(p, ext) {
    const b = trim(p).slice(trim(p).lastIndexOf('/') + 1);
    return ext && b !== ext && b.endsWith(ext) ? b.slice(0, -ext.length) : b;
  }
  function extname(p) {
    const b = basename(p);
    const i = b.lastIndexOf('.');
    return i > 0 ? b.slice(i) : '';
  }
  const shim = {
    normalize, join, dirname, basename, extname,
  };
  shim.posix = shim;
  return shim;
}

/* Read-only fs over the inlined text files. Other files (upload images) do not exist. */
function virtualFs(files) {
  const has = (p) => Object.hasOwn(files, p);
  const get = (p) => {
    if (!has(p)) throw new Error(`ENOENT: ${p}`);
    return files[p];
  };
  return {
    existsSync: has,
    readFileSync: get,
    statSync: (p) => get(p) && { isFile: () => true, isDirectory: () => false },
  };
}

/* CommonJS for the wrapped modules: module(module, exports, require, __dirname, process). */
function loader(modules, builtins, shim) {
  const cache = {};
  const proc = { env: {} };
  function load(file) {
    if (Object.hasOwn(builtins, file)) return builtins[file];
    if (!cache[file]) {
      if (!modules[file]) throw new Error(`preview: no module ${file}`);
      const module = { exports: {} };
      cache[file] = module;
      const dir = shim.dirname(file);
      const req = (n) => load(n.charAt(0) === '.' ? `${shim.join(dir, n)}.js` : n);
      modules[file](module, module.exports, req, dir, proc);
    }
    return cache[file].exports;
  }
  return load;
}

/* The renderPages context, with root '.' (the keys of the virtual fs). site: readSite() result. */
function renderPage(load, pages, newsHref, site, name, content) {
  const page = pages.find((p) => p.content === name);
  if (!page) throw new Error(`no preview for ${name}`);
  return load(page.file).render(content, {
    site,
    newsHref,
    page: { slug: page.slug, category: page.category, content: page.content },
    root: '.',
    projects: load('build/lib/projects.js').loadProjects('.'),
    posts: null,
    manifest: load('build/lib/images.js').readManifest('.'),
  });
}

/* Preview only: lazyload images get their real src (no theme JS in the pane). An upload
   without a manifest entry (a new CMS upload) gets the CMS asset URL. Variants stay. */
function forPreview(html, manifest, getAsset) {
  return html.replace(/<img\b[^>]*>/g, (tag) => {
    let t = tag;
    if (/\sclass="[^"]*\blazyload\b/.test(t) && /\sdata-src="/.test(t)) {
      t = t.replace(/\ssrc="data:[^"]*"/, '').replace(/\sdata-src="/, ' src="')
        .replace(/\sclass="([^"]*)"/, (m, c) => {
          const rest = c.split(/\s+/).filter((x) => x && x !== 'lazyload').join(' ');
          return rest ? ` class="${rest}"` : '';
        });
    }
    return t.replace(/\ssrc="\/(wp-content\/uploads\/[^"]*)"/, (m, v) => {
      let p;
      try {
        p = decodeURI(v);
      } catch {
        return m;
      }
      if (!getAsset || Object.hasOwn(manifest, p)) return m;
      const url = String(getAsset(`/${p}`));
      return url === `/${p}` || url === `/${v}` ? m : ` src="${url.replace(/"/g, '&quot;')}"`;
    });
  });
}

/* The blob: URL of an upload of the entry that is not published yet, else null.
   Decap 3.10+ takes a root-relative value such as /wp-content/uploads/news/x.jpg for a
   published URL (decap-cms #7639), so it does not find the upload in memory. */
function draftUrl(entry, p) {
  const files = entry && entry.get('mediaFiles');
  const list = files && files.toJS ? files.toJS() : [];
  const file = (Array.isArray(list) ? list : [])
    .find((f) => f.url && f.path && `/${f.path.replace(/^\//, '')}` === p);
  return file ? file.url : null;
}

/* Workarounds for Decap bugs (LND-035):
   - the image widget (its thumbnail and preview) and the body preview show an unpublished
     upload: draftUrl first, then Decap's getAsset;
   - "---" is a block component. Most posts start with "---": Decap's Slate serializer reads
     a leading bare thematic break as inline content and empties the body on any Rich Text
     edit. toBlock keeps the blank line before it: a body that starts with "---" does not
     save (gray-matter reads it as front matter). */
function patchCms(cms, h) {
  const withDrafts = (widget, entryOf) => (props) => h(widget, {
    ...props,
    getAsset: (p, field) => draftUrl(entryOf(props), p) || props.getAsset(p, field),
  });
  const wrap = (name, entryOfControl) => {
    const w = cms.getWidget(name);
    cms.registerWidget({
      name,
      controlComponent: entryOfControl ? withDrafts(w.control, entryOfControl) : w.control,
      previewComponent: withDrafts(w.preview, (props) => props.entry),
      schema: w.schema,
      allowMapValue: w.allowMapValue,
      globalStyles: w.globalStyles,
    });
  };
  wrap('image', (props) => props.getEntry && props.getEntry());
  wrap('markdown', null);
  cms.registerEditorComponent({
    id: 'separator',
    label: 'Separator',
    fields: [],
    pattern: /^---$/,
    fromBlock: () => ({}),
    toBlock: () => '\n---',
    toPreview: () => '<hr />',
  });
}

/* One Decap preview template per page. No allow-scripts: the theme JS does not run. */
function register(cms, h, pages, render, prepare, manifest) {
  pages.forEach(({ content }) => {
    cms.registerPreviewTemplate(content, (props) => {
      const getAsset = (p) => draftUrl(props.entry, p)
        || (props.getAsset ? props.getAsset(p) : p);
      let html;
      try {
        html = prepare(render(content, props.entry.get('data').toJS()), manifest, getAsset);
      } catch (err) {
        return h('p', null, `Preview not available: ${err.message}`);
      }
      return h('iframe', {
        srcDoc: html,
        sandbox: 'allow-same-origin',
        style: { border: 0, width: '100%', height: '100vh' },
      });
    });
  });
}

/* ---------- admin/preview.js ---------- */

/* The text of admin/preview.js: the build render modules over a virtual fs. */
function previewScript(root, manifest, newsHref) {
  const pages = previewPages(root);
  const modules = moduleSources(root, pages.map((p) => p.file));
  const wrapped = Object.entries(modules).map(([k, src]) => `${JSON.stringify(k)}: `
    + `function (module, exports, require, __dirname, process) {\n${src}\n}`).join(',\n');
  return `${HEADER}(function () {
var FILES = ${JSON.stringify(dataFiles(root, manifest))};
var MODULES = {
${wrapped}
};
var PAGES = ${JSON.stringify(pages)};
var NEWS_HREF = ${JSON.stringify(newsHref)};
var SITE = ${JSON.stringify(readSite(root))};
${pathShim}
${virtualFs}
${loader}
${renderPage}
${draftUrl}
${forPreview}
${register}
${patchCms}
var path = pathShim();
var empty = {};
var load = loader(MODULES, {
  'node:fs': virtualFs(FILES),
  'node:path': path,
  'node:os': empty,
  'node:crypto': empty,
  'node:module': empty,
  'node:child_process': empty
}, path);
var manifest = JSON.parse(FILES[${JSON.stringify(MANIFEST)}]);
function render(name, content) {
  return renderPage(load, PAGES, NEWS_HREF, SITE, name, content);
}
window.NellisPreview = { render: render, forPreview: forPreview };
if (window.CMS) {
  patchCms(window.CMS, window.h);
  register(window.CMS, window.h, PAGES, render, forPreview, manifest);
}
}());
`;
}

function writePreview(root, manifest, newsHref) {
  fs.writeFileSync(path.join(root, 'admin', 'preview.js'), previewScript(root, manifest, newsHref));
}

module.exports = {
  previewPages, previewScript, writePreview, forPreview, register, pathShim,
};
