const fs = require('node:fs');
const path = require('node:path');

const PATH_RE = /^\/[A-Za-z0-9._~/-]*$/;
const FIXED_FILE = 'build/redirects.txt';
const HEADER = '# Generated by build-news.js from build/redirects.txt, content/redirects.json '
  + 'and news slugs. Do not edit.\n';
const FIXED_FROM_RE = /^\/[A-Za-z0-9._~/:-]*(\/\*)?$/;
const FIXED_TO_RE = /^(\/[A-Za-z0-9._~/:-]*|https:\/\/\S+)$/;

const norm = (p) => (p.length > 1 ? p.replace(/\/+$/, '') : p);
const isPath = (p) => typeof p === 'string' && PATH_RE.test(p)
  && !p.includes('..') && !p.includes('//');
const isUrl = (p) => typeof p === 'string' && /^https:\/\/[^\s/]+(\/\S*)?$/.test(p);

function parseRules(json) {
  return (JSON.parse(json).redirects || []).map((r) => ({ from: r.from, to: r.to }));
}

function parseFixed(text) {
  return text.split('\n').flatMap((raw, i) => {
    const line = raw.trim();
    if (!line || line.startsWith('#')) return [];
    const [from, to, status, ...rest] = line.split(/\s+/);
    if (rest.length || !FIXED_FROM_RE.test(from) || !FIXED_TO_RE.test(to || '')
      || !['200', '301'].includes(status)) {
      throw new Error(`${FIXED_FILE} line ${i + 1}: "${line}" must be "from to status", `
        + 'status 200 or 301');
    }
    return [{ from, to, status: Number(status) }];
  });
}

const isDynamic = (r) => /[*:]/.test(r.from);

function fixedFroms(fixed) {
  return fixed.map((r) => ({ from: r.from, file: FIXED_FILE }));
}

/* A file at <p>, or <p>/index.html. */
// ponytail: macOS finds files in any case, the Linux build does not.
// A case-only typo in `to` passes locally and fails the Cloudflare build (fail-safe).
function onDisk(root) {
  return (p) => {
    const f = path.join(root, p);
    if (fs.existsSync(f) && fs.statSync(f).isFile()) return true;
    return fs.existsSync(path.join(f, 'index.html'));
  };
}

/* "/x/*" also matches "/x", ":name" matches one segment. The trailing slash is ignored. */
function hitsFixed(from, froms) {
  const hit = froms.find((f) => {
    const splat = f.from.endsWith('/*');
    const re = norm(splat ? f.from.slice(0, -2) : f.from).split('/')
      .map((s) => (s.startsWith(':') ? '[^/]+' : s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')))
      .join('/');
    return new RegExp(`^${re}${splat ? '(/.*)?' : ''}$`).test(norm(from));
  });
  return hit && hit.file;
}

function validate(rules, { exists, fixedFroms: froms }) {
  const errors = [];
  const seen = new Set();
  const map = new Map(rules.map((r) => [norm(String(r.from)), norm(String(r.to))]));
  rules.forEach(({ from, to }) => {
    const name = `redirect "${from} -> ${to}"`;
    const fail = (why) => errors.push(`${name}: ${why}`);
    if (!isPath(from)) {
      fail('"from" must be a path like /old-page/ (letters, digits, . _ ~ - /; no .. or //)');
      return;
    }
    if (isPath(to)) {
      if (!exists(to)) fail(`"to" ${to} does not exist on the site`);
    } else if (!isUrl(to)) {
      fail('"to" must be a path like /new-page/ or an https:// URL');
    }
    if (exists(from)) fail(`"from" ${from} is a live page or file; a 301 never shadows it`);
    const file = hitsFixed(from, froms);
    if (file) fail(`"from" ${from} matches a rule in ${file}`);
    if (norm(from) === '/admin' || from.startsWith('/admin/')) {
      fail('"from" must not be under /admin/');
    }
    if (norm(from) === norm(String(to))) fail('"from" and "to" are the same');
    if (seen.has(norm(from))) fail(`duplicate "from" ${from}`);
    seen.add(norm(from));
    if (norm(from) !== norm(String(to)) && map.get(norm(String(to))) === norm(from)) {
      fail(`loop: ${to} redirects back to ${from}`);
    }
  });
  return errors;
}

function autoNewsRules(posts) {
  return posts
    .filter((p) => p.filename !== p.slug)
    .map((p) => ({ from: `/news/${p.filename}/`, to: `/news/${p.slug}/` }));
}

/* Manual rules win. An auto rule that hits a live URL or a manual "from" is dropped. */
function mergeRules(manual, auto, exists) {
  const froms = new Set(manual.map((r) => norm(String(r.from))));
  return [...manual, ...auto.filter((r) => !exists(r.from) && !froms.has(norm(r.from)))];
}

/* Static fixed rules, CMS rules (both slash forms), then fixed rules with * or :name. */
function render(rules, fixed = []) {
  const line = (r) => `${r.from} ${r.to} ${r.status}\n`;
  const cms = rules.flatMap((r) => [norm(r.from), `${norm(r.from)}/`]
    .map((from) => line({ from, to: r.to, status: 301 })));
  return HEADER + fixed.filter((r) => !isDynamic(r)).map(line).join('') + cms.join('')
    + fixed.filter(isDynamic).map(line).join('');
}

module.exports = {
  FIXED_FILE,
  parseRules,
  parseFixed,
  fixedFroms,
  hitsFixed,
  onDisk,
  validate,
  autoNewsRules,
  mergeRules,
  render,
};
